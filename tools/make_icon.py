#!/usr/bin/env python3
"""Builds the adaptive launcher icon from the bundled outline of Hungary.

Writes res/drawable/ic_launcher_{foreground,background,monochrome}.xml and, with --preview DIR,
an SVG/PNG preview (needs rsvg-convert). Requires shapely.
"""
import argparse
import json
import math
import pathlib
import subprocess

from shapely.geometry import Polygon, shape

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "app/src/main/assets/map"
DRAWABLE = ROOT / "app/src/main/res/drawable"

INK, INK2, PAPER, AMBER = "1B2A44", "2C4166", "F7F1E4", "E09A2D"
WIDTH = 68.0  # dp of the 108 dp canvas; the 66 dp safe circle cuts only the far tips


def geometry():
    outline = shape(json.loads((ASSETS / "outline.geojson").read_text())["features"][0]["geometry"])
    budapest = next(c for c in json.loads((ASSETS / "cities.json").read_text()) if c["id"] == "budapest")
    k = math.cos(math.radians(47.2))
    proj = Polygon([(x * k, -y) for x, y in outline.exterior.coords])
    minx, miny, maxx, maxy = proj.bounds
    s = WIDTH / (maxx - minx)
    ox, oy = (108 - WIDTH) / 2, (108 - (maxy - miny) * s) / 2 + 2.5
    simple = proj.simplify((maxx - minx) / 260, preserve_topology=True)
    pts = [((x - minx) * s + ox, (y - miny) * s + oy) for x, y in simple.exterior.coords]
    path = "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"
    bx, by = (budapest["lon"] * k - minx) * s + ox, (-budapest["lat"] - miny) * s + oy
    return path, bx, by


def pin(bx, by, r=6.0, lift=12.0):
    cy = by - lift
    ang = math.asin(r / lift)
    tx, ty = r * math.cos(ang), cy + r * math.sin(ang)
    body = f"M{bx:.2f},{by:.2f} L{bx - tx:.2f},{ty:.2f} A{r},{r} 0 1,1 {bx + tx:.2f},{ty:.2f} Z"
    d = 2.3
    dot = f"M{bx - d:.2f},{cy:.2f} a{d},{d} 0 1,0 {2 * d},0 a{d},{d} 0 1,0 {-2 * d},0 Z"
    return body, dot


VECTOR = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
          '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=pathlib.Path)
    args = ap.parse_args()
    country, bx, by = geometry()
    body, dot = pin(bx, by)
    head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icon.py; outline © OpenStreetMap contributors (ODbL). -->\n'

    (DRAWABLE / "ic_launcher_foreground.xml").write_text(head + VECTOR.format(ns="") + f"""\
    <group android:translateX="0.9" android:translateY="1.8">
        <path android:fillColor="#40000000" android:pathData="{country}" />
    </group>
    <path android:fillColor="#FF{PAPER}" android:pathData="{country}" />
    <group android:translateX="0.5" android:translateY="1">
        <path android:fillColor="#33000000" android:pathData="{body}" />
    </group>
    <path android:fillColor="#FF{AMBER}" android:strokeColor="#FF{INK}" android:strokeWidth="0.9" android:pathData="{body}" />
    <path android:fillColor="#FF{INK}" android:pathData="{dot}" />
</vector>
""")
    (DRAWABLE / "ic_launcher_monochrome.xml").write_text(head + VECTOR.format(ns="") + f"""\
    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{country} {body} {dot}" />
</vector>
""")
    (DRAWABLE / "ic_launcher_background.xml").write_text(
        head + VECTOR.format(ns='\n    xmlns:aapt="http://schemas.android.com/aapt"') + f"""\
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108"
                android:startColor="#FF{INK2}" android:endColor="#FF{INK}" />
        </aapt:attr>
    </path>
    <path android:fillColor="#14FFFFFF" android:pathData="M54,54m-40,0a40,40 0 1,1 80,0a40,40 0 1,1 -80,0" />
</vector>
""")

    if args.preview:
        args.preview.mkdir(parents=True, exist_ok=True)
        layers = f"""<rect width="108" height="108" fill="url(#g)"/>
<circle cx="54" cy="54" r="40" fill="#fff" fill-opacity="0.08"/>
<path transform="translate(0.9,1.8)" d="{country}" fill="#000" fill-opacity="0.25"/>
<path d="{country}" fill="#{PAPER}"/>
<path transform="translate(0.5,1)" d="{body}" fill="#000" fill-opacity="0.2"/>
<path d="{body}" fill="#{AMBER}" stroke="#{INK}" stroke-width="0.9"/>
<path d="{dot}" fill="#{INK}"/>"""
        defs = f"""<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#{INK2}"/>
<stop offset="1" stop-color="#{INK}"/></linearGradient><clipPath id="c"><rect x="9" y="9" width="90" height="90" rx="26"/></clipPath></defs>"""
        icon = f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="9 9 90 90">{defs}<g clip-path="url(#c)">{layers}</g></svg>'
        (args.preview / "icon.svg").write_text(icon)
        subprocess.run(["rsvg-convert", str(args.preview / "icon.svg"), "-o", str(args.preview / "icon.png")], check=True)


if __name__ == "__main__":
    main()
